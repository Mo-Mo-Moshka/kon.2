FALLBACK = GLYPHS["?"]


def glyph(symbol: str) -> tuple[str, ...]:
    """Изображение символа; строчные буквы выводятся заглавными."""
    if symbol in GLYPHS:
        return GLYPHS[symbol]
    upper = symbol.upper()
    return GLYPHS.get(upper, FALLBACK)


def text_width(text: str, scale: int = 1, spacing: int = 1) -> int:
    """Ширина надписи в пикселях."""
    if not text:
        return 0
    return (len(text) * (WIDTH + spacing) - spacing) * scale


def text_height(scale: int = 1) -> int:
    """Высота надписи в пикселях."""
    return HEIGHT * scale
